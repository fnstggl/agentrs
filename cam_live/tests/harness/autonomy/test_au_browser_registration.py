"""AU (browser, real Chromium): registering an account on a service that is not CAM's -- the path the harness
offers where automated registration is permitted. Live mode, standing record, a local service standing in for the
third-party site (no external contact). Reading the sign-up page is a read; every input into it waits for the
operator (approval retained for input on sites the operator does not own); the account's password is generated by
the operator's credential tool, typed by reference, and never appears outside the vault."""
import json
import os
import shutil
import tempfile
import time
from urllib.parse import parse_qs

import pytest

from cam_live import contracts as C
from cam_live.harness import credentials as CR
from cam_live.harness.auth import PolicyService
from cam_live.harness.browser import BrowserExecutor
from cam_live.harness.env import ComputerEnvironment
from cam_live.harness.internal import InternalExecutor

from au_support import ALLOW, NEEDS, PROFILE, files_containing, live_task, sign_register, standing_record
from e_fix_support import CountingServer, html

pytestmark = pytest.mark.browser


@pytest.fixture
def rig(tmp_path):
    srv = CountingServer()
    got = []
    srv.page("/signup", html("Create an account", """<h1>Create an account</h1>
      <form method=post action=/register><label>E-mail <input id=email name=email></label>
      <label>Password <input id=pw name=password type=password></label><button id=go>Create</button></form>"""))

    def register(method, path, q, headers, body):
        got.append((method, body))
        return 200, {}, html("done", "<p>account created</p>")
    srv.routes["/register"] = register
    base = tempfile.mkdtemp(prefix="camlive-au-br-", dir="/tmp")
    run_dir = os.path.join(base, "run")
    os.makedirs(run_dir)
    svc = PolicyService(run_dir, fsync=False)
    svc.register_local_service(srv.host, by="operator", note="stands in for a third-party service")
    t = live_task(oid="obj-au-register", interfaces=["structured_browser", "internal"], resources={})
    sign_register(svc, tmp_path, standing_record(t, time.time(), read=[srv.host],
                                                 standing={"profile": PROFILE, "code_network": []}))
    svc.register_task(t, "operator")
    # the operator generates the account's password, bound to the service and to typing it into a form
    assert CR.main(["set", "svc_password", "--run-dir", run_dir, "--dest", srv.url + "/*", "--op", "browser.fill",
                    "--generate", "--no-verifier"]) == 0
    pw = json.load(open(os.path.join(run_dir, "vault", "svc_password.secret.json")))["value"]
    env = ComputerEnvironment(run_dir, svc, secrets=svc.secrets_handle(), provenance="staging")
    env.register(InternalExecutor(run_dir, clock=env.clock))
    env.register(BrowserExecutor(run_dir, clock=env.clock))
    yield dict(srv=srv, got=got, svc=svc, env=env, task=t, run_dir=run_dir, pw=pw)
    env.close()
    svc.close()
    srv.close()
    shutil.rmtree(base, ignore_errors=True)


def step(w, op, **args):
    a = C.ActionSpec(action_id=C.new_id("act"), operation=op, modality=C.Modality.STRUCTURED_BROWSER, arguments=args)
    d = w["svc"].authorize(a, w["task"], {})
    return a, d


def test_registration_elsewhere_runs_only_with_the_operators_approvals_and_the_password_stays_in_the_vault(rig):
    w = rig
    a, d = step(w, "browser.navigate", url=w["srv"].url + "/signup")
    assert d.verdict == ALLOW, d.reasons                    # reading the page: a read
    assert w["env"].execute(a, d).status == C.ResultStatus.OK
    results = {}
    for name, args in (("email", dict(selector="#email", text="cam-automated@mail.example")),
                       ("password", dict(selector="#pw", secret="secret:svc_password"))):
        a, d = step(w, "browser.fill", **args)
        assert d.verdict == NEEDS and "P-INTERACT-APPROVAL" in d.policy_ids, (name, d.verdict, d.reasons)
        w["svc"].resolve_approval(d.approval_id, True, "operator")
        d = w["svc"].authorize(a, w["task"], {})
        assert d.verdict == ALLOW
        results[name] = w["env"].execute(a, d)
        assert results[name].status == C.ResultStatus.OK, (name, results[name].failure_detail)
    # submitting the form is a click (navigation class): allowed; what it sends was approved field by field
    a, d = step(w, "browser.click", selector="#go")
    assert d.verdict == ALLOW, (d.verdict, d.reasons)
    results["click"] = w["env"].execute(a, d)
    assert results["click"].status == C.ResultStatus.OK
    deadline = time.time() + 10
    while time.time() < deadline and not w["got"]:
        time.sleep(0.2)
    posted = [parse_qs(b.decode()) for m, b in w["got"] if m == "POST"]
    assert len(posted) == 1 and posted[0]["password"] == [w["pw"]], posted
    assert posted[0]["email"] == ["cam-automated@mail.example"]
    # the password never left the vault into a record, an observation or a log
    assert files_containing(w["run_dir"], w["pw"]) == ["vault/svc_password.secret.json"]
    for r in results.values():
        if isinstance(r, C.ActionResult):
            assert w["pw"] not in json.dumps(r.to_dict(), default=str)


def test_without_the_approval_nothing_is_typed_into_the_service(rig):
    w = rig
    a, d = step(w, "browser.navigate", url=w["srv"].url + "/signup")
    assert w["env"].execute(a, d).status == C.ResultStatus.OK
    a, d = step(w, "browser.fill", selector="#pw", secret="secret:svc_password")
    assert d.verdict == NEEDS
    w["svc"].resolve_approval(d.approval_id, False, "operator", "not this service")
    d = w["svc"].authorize(a, w["task"], {})
    assert d.verdict != ALLOW
    a, d = step(w, "browser.click", selector="#go")
    w["env"].execute(a, d)
    time.sleep(1.0)
    posted = [parse_qs(b.decode()) for m, b in w["got"] if m == "POST"]
    assert all(p.get("password", [""]) == [""] or "password" not in p for p in posted), posted
