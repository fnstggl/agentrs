def _mean(x, valid):
    w = valid.to(x.dtype)
    return (x * w).sum() / w.sum().clamp(min=1.0)


def _gae(reward, value, done, trunc, valid, gamma, lam, delta_clip=0.0):
    """Generalised advantage estimation over whole episodes (terminal: bootstrap 0; truncated: own last value)."""
    B, T = reward.shape
    adv = torch.zeros_like(reward)
    last = torch.zeros(B, device=reward.device, dtype=reward.dtype)
    vnext = torch.zeros(B, device=reward.device, dtype=reward.dtype)
    v = value.detach()
    for t in range(T - 1, -1, -1):
        m = valid[:, t].to(reward.dtype)
        is_last = (done[:, t] + trunc[:, t]).clamp(max=1.0)
        nv = torch.where(trunc[:, t] > 0, v[:, t], vnext) * (1.0 - done[:, t])
        delta = reward[:, t] + gamma * nv - v[:, t]
        if delta_clip > 0:
            delta = delta.clamp(-delta_clip, delta_clip)
        last = (delta + gamma * lam * (1.0 - is_last) * last) * m
        adv[:, t] = last
        vnext = torch.where(m > 0, v[:, t], vnext)
    return adv

