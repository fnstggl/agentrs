def _sample_params(spec: dict, rng) -> dict:
    return {k: round(float(rng.uniform(lo, hi)), 3) for k, (lo, hi) in spec.items()}


def render_rule(genome: dict) -> str:
    parts, why = [], []
    genome = dict(genome)
    genome.setdefault("rep", ["none", {}])
    for slot in SLOT_ORDER:
        table, _ = SLOT_TABLE[slot]
        name, params = genome[slot]
        why.append(f"{slot}={name}{params or ''}")
        parts.append(table[name][2].format(**params) if params else table[name][2].format())
    doc = "Composition: " + "; ".join(why) + "."
    return HEADER.format(doc=doc, **genome["consts"]) + "\n".join(p.strip("\n") + "\n\n" for p in parts[:3]) \
        + FIXED.strip("\n") + "\n\n\n" + parts[3].strip("\n") + "\n\n\n" + parts[4].strip("\n") + "\n"


def genome_hypothesis(genome: dict, base: dict) -> tuple[str, list[str]]:
    reasons, slots = [], []
    for slot in SLOT_ORDER:
        if genome.get(slot, ["none", {}]) != base.get(slot, ["none", {}]):
            table, fn = SLOT_TABLE[slot]
            reasons.append(f"{fn} -> {genome[slot][0]} {genome[slot][1]}: {table[genome[slot][0]][0]}")
            slots.append(fn)
    dc = {k: v for k, v in genome["consts"].items() if abs(v - base["consts"][k]) > 1e-9}
    if dc:
        reasons.append(f"constants {dc}")
        slots.append("other")
    return " ; ".join(reasons) or "no change", slots


class RuleSpace:
    def __init__(self, seed: int = 0):
        self.rng = np.random.default_rng(seed)
        self.n = 0

    def mutate(self, genome: dict, strength: float = 1.0) -> dict:
        g = copy.deepcopy(genome)
        r = self.rng
        k = r.random()
        g.setdefault("rep", ["none", {}])
        if k < 0.7:
            slot = SLOT_ORDER[int(r.integers(0, len(SLOT_ORDER)))]
            table, _ = SLOT_TABLE[slot]
            if g[slot][1] and r.random() < 0.35:              # perturb the fragment's own constants
                spec = table[g[slot][0]][1]
                key = list(spec)[int(r.integers(0, len(spec)))]
                lo, hi = spec[key]
                g[slot][1][key] = round(float(np.clip(g[slot][1][key] + r.normal(0, 0.2 * strength) * (hi - lo), lo, hi)), 3)
            else:                                             # replace the fragment
                names = [n for n in table if n != g[slot][0]]
                name = names[int(r.integers(0, len(names)))]
                g[slot] = [name, _sample_params(table[name][1], r)]
        else:
            key = list(CONST_RANGES)[int(r.integers(0, len(CONST_RANGES)))]
            lo, hi = CONST_RANGES[key]
            g["consts"][key] = round(float(np.clip(g["consts"][key] + r.normal(0, 0.25 * strength) * (hi - lo), lo, hi)), 4)
        return g

    def crossover(self, a: dict, b: dict) -> dict:
        g = copy.deepcopy(a)
        for slot in SLOT_ORDER:
            if self.rng.random() < 0.5 and slot in b:
                g[slot] = copy.deepcopy(b[slot])
        return g

    def propose(self, parent: dict, n_mut: int | None = None, other: dict | None = None) -> dict:
        g = self.crossover(parent, other) if other is not None and self.rng.random() < 0.3 else copy.deepcopy(parent)
        for _ in range(n_mut or int(self.rng.integers(1, 3))):
            g = self.mutate(g)
        if g == parent:
            g = self.mutate(g)
        hyp, slots = genome_hypothesis(g, parent)
        self.n += 1
        return make_proposal("rule_space", hyp, "a higher area under the held-out learning curve at equal experience",
                             {RULE_PATH: render_rule(g)}, slots, genome=g)


# ================================================================================================ learned rule
LEARNED = '''
PHI = {phi}


def _eta(x):
    """The meta-network: 5 inputs -> 8 tanh units -> 1 output; its 57 weights are PHI[:57]."""
    p = torch.tensor(PHI, dtype=x.dtype, device=x.device)
    w1, b1, w2, b2 = p[:40].view(8, 5), p[40:48], p[48:56], p[56]
    return torch.tanh(x @ w1.t() + b1) @ w2 + b2


def advantages(reward, value, done, trunc, valid, cfg: RuleConfig):
    lam = float(torch.sigmoid(torch.tensor(PHI[57])))                 # learned credit-assignment horizon
    adv = _gae(reward, value, done, trunc, valid, cfg.gamma, lam)
    return adv, adv + value.detach() * valid.to(reward.dtype)


def policy_loss(logp, logp_old, adv, valid, cfg: RuleConfig):
    ratio = torch.exp((logp - logp_old).clamp(-20, 20))
    eps = 0.4 * float(torch.sigmoid(torch.tensor(PHI[58])))           # learned trust region
    with torch.no_grad():
        x = torch.stack([adv, ratio - 1.0, adv * (ratio - 1.0), adv.abs(), torch.ones_like(adv)], -1)
        wts = 1.0 + 0.9 * torch.tanh(_eta(x))                         # learned per-decision weight in (0.1, 1.9)
    loss = -_mean(wts * torch.min(ratio * adv, ratio.clamp(1.0 - eps, 1.0 + eps) * adv), valid)
    with torch.no_grad():
        info = {{"kl": float(_mean(logp_old - logp, valid)),
                "clip_frac": float(_mean(((ratio - 1.0).abs() > eps).to(logp.dtype), valid))}}
    return loss, info
'''
PHI_DIM = 59


def phi_init() -> np.ndarray:
    """Start at the baseline rule: zero meta-network (all weights 1), lambda = 0.95, clip = 0.2."""
    phi = np.zeros(PHI_DIM)
    phi[57] = float(np.log(0.95 / 0.05))
    phi[58] = 0.0            # 0.4 * sigmoid(0) = 0.2
    return phi


def render_learned(phi: np.ndarray, consts: dict | None = None) -> str:
    c = dict(BASE_CONSTS, **(consts or {}))
    body = LEARNED.format(phi=json.dumps([round(float(x), 5) for x in phi]))
    return (HEADER.format(doc="Learned rule: a meta-network weights the policy gradient per decision; its "
                              "parameters PHI were found by an evolution strategy over inner training runs.", **c)
            + body.strip("\n") + "\n\n\n" + VAL["mse"][2].strip("\n") + "\n\n" + FIXED.strip("\n") + "\n\n\n"
            + TOT["sum"][2].strip("\n") + "\n\n\n" + REP["none"][2].strip("\n") + "\n")


class LearnedRule:
    """Evolution strategy over PHI (antithetic Gaussian perturbations, rank-shaped update of the mean)."""

    def __init__(self, seed: int = 0, sigma: float = 0.35, lr: float = 0.6):
        self.rng = np.random.default_rng(seed)
        self.mean = phi_init()
        self.sigma, self.lr = sigma, lr
        self.gen = 0
        self.pending: dict[str, np.ndarray] = {}
        self.results: list[tuple[np.ndarray, float]] = []
        self.history: list[dict] = []
        self._anti: np.ndarray | None = None

    def propose(self) -> dict:
        if self._anti is not None:
            eps, self._anti = -self._anti, None
        else:
            eps = self.rng.normal(size=PHI_DIM)
            self._anti = eps
        phi = self.mean + self.sigma * eps
        p = make_proposal("learned_rule",
                          f"learned update rule, generation {self.gen}: per-decision policy-gradient weights from a "
                          f"meta-network, learned lambda {1 / (1 + np.exp(-phi[57])):.3f} and clip {0.4 / (1 + np.exp(-phi[58])):.3f}",
                          "a higher area under the held-out learning curve at equal experience",
                          {RULE_PATH: render_learned(phi)}, ["policy_loss", "advantages"], genome={"phi": phi.tolist()})
        p["generation"] = self.gen
        self.pending[p["id"]] = eps
        return p

    def tell(self, pid: str, fitness: float | None) -> None:
        eps = self.pending.pop(pid, None)
        if eps is not None and fitness is not None:
            self.results.append((eps, float(fitness)))

    def step(self, min_results: int = 4) -> dict | None:
        """Move the mean along the rank-weighted perturbations of the finished generation."""
        if len(self.results) < min_results:
            return None
        f = np.array([r[1] for r in self.results])
        ranks = np.argsort(np.argsort(f)).astype(float)
        u = ranks / max(1, len(f) - 1) - 0.5
        grad = sum(ui * e for ui, (e, _) in zip(u, self.results)) / len(f)
        self.mean = self.mean + self.lr * self.sigma * grad * np.sqrt(PHI_DIM) / max(1e-9, np.linalg.norm(grad)) * 0.25 \
            if np.linalg.norm(grad) > 0 else self.mean
        rec = {"generation": self.gen, "n": len(f), "fitness_mean": float(f.mean()), "fitness_best": float(f.max()),
               "mean_norm": float(np.linalg.norm(self.mean - phi_init()))}
        self.history.append(rec)
        self.results = []
        self.gen += 1
        return rec

    def state_dict(self) -> dict:
        return {"mean": self.mean.tolist(), "gen": self.gen, "history": self.history, "sigma": self.sigma}

    def load_state_dict(self, s: dict) -> None:
        self.mean, self.gen = np.asarray(s["mean"]), s.get("gen", 0)
        self.history, self.sigma = list(s.get("history", [])), s.get("sigma", self.sigma)


