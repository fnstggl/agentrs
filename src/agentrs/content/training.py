"""Training for content actions: imitation, world-model prediction error, and content-level RL.

ContentPolicyRLTrainer — the content-generation weights are updated by policy gradient from
VERIFIED environment rewards. For an executed content action a = (op, c_1..c_N):

    log pi(a | s) = log pi(op | s) + sum_i log pi(c_i | s, op, c_<i)

Objective (token-level clipped surrogate, GRPO-style group advantages):

    L = - E[ sum_{units u in {op, c_1..c_N}} min(rho_u A, clip(rho_u, 1-eps, 1+eps) A) ]
        + beta * sum_i KL(pi(.|s, c_<i) || pi_ref(.|s, c_<i))

with rho_u = exp(log pi_theta(u) - log mu(u)) computed from the EXACT stored token ids and their
stored behaviour log-probs (mu = the policy checkpoint that generated them). On fresh on-policy
data rho = 1 and the gradient equals -A * grad sum_i log pi(c_i). One outcome scores the whole
sequence: it is a noisy sequence-level signal, not per-token credit (finer attribution is a
research extension). Only content generated by a trainable policy WITH stored behaviour
log-probs is used; teacher/human/dataset content (no behaviour probabilities) and
planner-selected drafts are excluded from the policy gradient (they feed imitation / the world
model instead). Rewards come only from the environment (``Transition.reward``), never from
model-generated text or predicted values. KL is exact over the full vocabulary at every
content position.
"""

from __future__ import annotations

import random
from collections import defaultdict
from dataclasses import dataclass
from typing import Optional, Sequence

import numpy as np
import torch
from pydantic import BaseModel, ConfigDict, Field

from agentrs.content.policy import ContentGeneratingPolicy, op_text
from agentrs.content.world_model import ContentConditionedWorldModel, content_targets
