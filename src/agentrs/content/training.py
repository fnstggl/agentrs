# --------------------------------------------------------------------------- imitation


class ContentBCConfig(BaseModel):
    model_config = ConfigDict(extra="forbid")
    steps: int = 300
    batch_size: int = 16
    optim: OptimConfig = Field(default_factory=lambda: OptimConfig(lr=5e-4, total_steps=300, warmup_steps=20,
                                                                   schedule="cosine"))
    w_success: float = 1.0
    w_failure: float = 0.0
    w_unknown: float = 0.3
    rehearsal_weight: float = 0.0  # mix in high-level (MiniWeb) BC loss to protect old skills
    seed: int = 0


@dataclass
class ContentDemo:
    prompt: str
    op_cands: list[str]
    op_index: int
    gen_prompt: str
    token_ids: list[int]
    weight: float


def content_demos(cp: ContentGeneratingPolicy, ts: Sequence[Transition], cfg: ContentBCConfig) -> list[ContentDemo]:
    from agentrs.actions.schema import ActionType, try_parse_action
    from agentrs.content.policy import generation_prompt

    out = []
    for t in ts:
        a = try_parse_action(t.action)
        if a is None or a.type != ActionType.SUBMIT or not t.belief_prompt:
            continue
        w = cfg.w_success if t.episode_success else (cfg.w_failure if t.episode_success is False else cfg.w_unknown)
        if t.content_outcome and t.content_outcome.get("objective_met"):
            w = cfg.w_success  # a step that itself met the objective is a good demonstration
        if w <= 0:
            continue
        cands = [try_parse_action(c) for c in t.candidates] if t.candidates else [a]
        cands = [c for c in cands if c is not None]
        ops = [op_text(c) for c in cands]
        k = ops.index(op_text(a)) if op_text(a) in ops else None
        if k is None:
            ops.append(op_text(a))
            k = len(ops) - 1
        gp = generation_prompt(t.belief_prompt, a.name or "")
        out.append(ContentDemo(t.belief_prompt, ops, k, gp, cp.demo_token_ids(a.text or ""), w))
    return out


def content_bc_loss(cp: ContentGeneratingPolicy, batch: Sequence[ContentDemo]) -> tuple[torch.Tensor, dict]:
    scores = cp.bb.score([b.prompt for b in batch], [b.op_cands for b in batch],
                         prefix_cache=cp.policy.cfg.prefix_cache, vocab_restrict=cp.policy.cfg.vocab_restrict)
    op_nll = torch.stack([-torch.log_softmax(s, 0)[b.op_index] for s, b in zip(scores, batch)])
    lp, mask = cp.content_log_probs([b.gen_prompt for b in batch], [b.token_ids for b in batch])
    tok_nll = -(lp * mask).sum(-1) / mask.sum(-1).clamp(min=1)
    w = torch.tensor([b.weight for b in batch], device=lp.device)
    loss = (w * (op_nll + tok_nll)).sum() / w.sum()
    return loss, {"op_nll": float(op_nll.detach().mean()), "content_nll_per_token": float(tok_nll.detach().mean())}


def train_content_bc(cp: ContentGeneratingPolicy, demos_ts: Sequence[Transition], cfg: ContentBCConfig,
                     rehearsal: Optional[list] = None, trainer: Optional[GradientTrainer] = None,
                     tracker=None) -> dict:
    """Imitation of demonstrated operations + content (teacher forcing). ``rehearsal`` = MiniWeb
    BCExamples mixed in so that learning content does not erase high-level action skills."""
    from agentrs.training.bc import bc_loss

    rng = random.Random(cfg.seed)
    demos = content_demos(cp, demos_ts, cfg)
    if not demos:
        raise ValueError("no usable content demonstrations")
    trainer = trainer or GradientTrainer(cp.policy, cfg.optim)
    hist = []
    for step in range(cfg.steps):
        b = rng.sample(demos, min(cfg.batch_size, len(demos)))
        loss, st = content_bc_loss(cp, b)
        if rehearsal and cfg.rehearsal_weight > 0:
            rl, _ = bc_loss(cp.policy, rng.sample(rehearsal, min(cfg.batch_size, len(rehearsal))))
            loss = loss + cfg.rehearsal_weight * rl
            st["rehearsal_loss"] = float(rl.detach())
        upd = trainer.step(loss)
        rec = {"loss": float(loss.detach()), **st, **upd}
        hist.append(rec)
        if tracker:
            tracker.log(rec, step, prefix="content_bc/")
    return {"n_demos": len(demos), "history": hist, "trainer": trainer,
            "first10": float(np.mean([h["loss"] for h in hist[:10]])),
            "last10": float(np.mean([h["loss"] for h in hist[-10:]]))}


# --------------------------------------------------------------------------- world model


class ContentWMTrainConfig(BaseModel):
    model_config = ConfigDict(extra="forbid")
    steps: int = 300
    batch_size: int = 16
    optim: OptimConfig = Field(default_factory=lambda: OptimConfig(lr=1e-3, total_steps=100000))
    seed: int = 0


@dataclass
class ContentWMExample:
    prompt: str
    diff: str
    targets: list[float]
    key: str
    content_targets: Optional[list[float]]
    chunk_prompts: Optional[list[str]]
    transition: Transition


def content_wm_examples(wm: ContentConditionedWorldModel, ts: Sequence[Transition]) -> list[ContentWMExample]:
    real = [t for t in ts if t.is_real]
    hists = episode_histories(real)
    out = []
    for t in real:
        h = hists.get((t.episode_id, t.step), [])
        groups = wm.action_prompts(t.goal, t.observation, t.action, h)
        out.append(ContentWMExample(prompt=wm.prompt(t.goal, t.observation, t.action, h), diff=t.diff_text or "(no change)",
                                    targets=targets_from_transition(t.events, t.reward, t.terminated),
                                    key=f"{t.episode_id}:{t.step}", content_targets=content_targets(t.content_outcome),
                                    chunk_prompts=groups if len(groups) > 1 else None, transition=t))
    return out


class ContentPredictionTrainer:
    """Trains the content-conditioned world model on real (content, context, outcome)
    transitions — own experience and authorised third-party examples alike — and measures its
    prediction error on held-out content. Separate optimiser state from the policy."""

    def __init__(self, wm: ContentConditionedWorldModel, cfg: ContentWMTrainConfig):
        self.wm, self.cfg = wm, cfg
        self.trainer = GradientTrainer(wm, cfg.optim)
        self.rng = random.Random(cfg.seed)

    def loss(self, batch: Sequence[ContentWMExample]):
        tg = torch.tensor([b.targets for b in batch], dtype=torch.float32)
        return self.wm.content_loss([b.prompt for b in batch], [b.diff for b in batch], tg, [b.key for b in batch],
                                    [b.content_targets for b in batch], [b.chunk_prompts for b in batch])

    def train(self, ts: Sequence[Transition], steps: Optional[int] = None) -> dict:
        ex = content_wm_examples(self.wm, ts)
        if not ex:
            raise ValueError("no real transitions")
        hist = []
        self.wm.train()
        for _ in range(steps if steps is not None else self.cfg.steps):
            b = self.rng.sample(ex, min(self.cfg.batch_size, len(ex)))
            loss, st = self.loss(b)
            upd = self.trainer.step(loss)
            hist.append({"loss": float(loss.detach()), **st, **upd})
        return {"n": len(ex), "history": hist, "first10": float(np.mean([h["loss"] for h in hist[:10]])),
                "last10": float(np.mean([h["loss"] for h in hist[-10:]]))}

    @torch.no_grad()
    def evaluate(self, ts: Sequence[Transition]) -> dict:
        """Held-out content prediction: NLL / Brier / ECE / AUROC of P(objective met)."""
        from agentrs.evaluation.metrics import auroc, bernoulli_nll, brier, expected_calibration_error

        ex = [e for e in content_wm_examples(self.wm, ts) if e.content_targets is not None]
        if not ex:
            return {}
        self.wm.eval()
        probs, ys, stds = [], [], []
        hists = episode_histories([e.transition for e in ex])
        for e in ex:
            t = e.transition
            p = self.wm.predict_content(t.goal, t.observation, [t.action], hists.get((t.episode_id, t.step), []))[0]
            probs.append(p.p_objective)
            stds.append(p.epistemic)
            ys.append(e.content_targets[1])
        err = (np.abs(np.asarray(probs) - np.asarray(ys)) > 0.5).astype(float)
        self.wm.train()
        return {"n": len(ex), "objective_nll": bernoulli_nll(probs, ys), "objective_brier": brier(probs, ys),
                "objective_ece": expected_calibration_error(probs, ys), "objective_auroc": auroc(probs, ys),
                "base_rate": float(np.mean(ys)), "uncertainty_flags_error_auroc": auroc(stds, err)}


# --------------------------------------------------------------------------- content RL


class ContentRLConfig(BaseModel):
    model_config = ConfigDict(extra="forbid")
    clip_eps: float = 0.2
    kl_coef: float = 0.02
    epochs: int = 1
    minibatch_size: int = 16
    token_reduction: str = "sum"  # sum (= the stated objective) | mean (per-token average)
    invalid_penalty: float = 0.1
    advantage: str = "group"  # group (GRPO: per task) | batch (batch-mean baseline)
    optim: OptimConfig = Field(default_factory=lambda: OptimConfig(lr=3e-5, total_steps=100000))
    imagined_weight: float = 0.5


@dataclass
class ContentRLStep:
    prompt: str
    op_cands: list[str]
    op_index: int
    op_logprob_old: float
    gen_prompt: str
    token_ids: list[int]
    token_logprobs_old: list[float]
    advantage: float
    checkpoint: Optional[str]
    weight: float = 1.0
    imagined: bool = False


def eligible_for_pg(t: Transition) -> tuple[bool, str]:
    sa = t.semantic_action
    if sa is None:
        return False, "not a content action"
    if t.provenance.source in (Source.TEACHER, Source.HUMAN, Source.DATASET, Source.INFERRED):
        return False, "third-party content has no behaviour log-probs from this policy"
    if t.selection != "policy" or sa.source != "policy":
        return False, "not sampled from the policy (planner/greedy/other selection)"
    if not sa.has_behavior_logprobs:
        return False, "missing behaviour log-probs or token ids"
    if sa.sampling_temperature not in (None, 1.0):
        return False, "sampled at T != 1 (behaviour != policy)"
    if sa.execution_status not in ("executed", "rejected"):
        return False, f"not executed ({sa.execution_status})"
    return True, ""


def build_content_rl_steps(episodes: Sequence[Sequence[Transition]], cfg: ContentRLConfig) -> tuple[list[ContentRLStep], dict]:
    """Episode returns come from verified environment rewards only. Every content action in an
    episode shares that episode's (group-normalised) advantage."""
    rets = {}
    for ep in episodes:
        R = sum(float(t.reward) for t in ep) - cfg.invalid_penalty * sum(not t.action_valid for t in ep)
        rets[ep[0].episode_id] = (ep[0].task_id, R)
    groups: dict[str, list[float]] = defaultdict(list)
    for tid, R in rets.values():
        groups[tid].append(R)
    allR = [R for _, R in rets.values()]
    steps, rejected = [], defaultdict(int)
    for ep in episodes:
        tid, R = rets[ep[0].episode_id]
        if cfg.advantage == "group" and len(groups[tid]) > 1:
            g = np.asarray(groups[tid])
            A = (R - g.mean()) / (g.std() + 1e-6)
        else:
            A = (R - float(np.mean(allR))) / (float(np.std(allR)) + 1e-6)
        for t in ep:
            ok, why = eligible_for_pg(t)
            if not ok:
                rejected[why] += 1
                continue
            sa = t.semantic_action
            steps.append(ContentRLStep(prompt=t.belief_prompt or sa.context, op_cands=sa.op_candidates,
                                       op_index=sa.op_index, op_logprob_old=sa.op_logprob,
                                       gen_prompt=sa.generation_prompt, token_ids=sa.token_ids,
                                       token_logprobs_old=sa.token_logprobs, advantage=float(A),
                                       checkpoint=sa.policy_checkpoint))
    return steps, dict(rejected)


class ContentPolicyRLTrainer:
    def __init__(self, cp: ContentGeneratingPolicy, cfg: ContentRLConfig, ref: Optional[ContentGeneratingPolicy] = None,
                 seed: int = 0):
        self.cp, self.cfg, self.ref = cp, cfg, ref
        self.trainer = GradientTrainer(cp.policy, cfg.optim)
        self.rng = random.Random(seed)
        self.version = 0

    def loss(self, batch: Sequence[ContentRLStep]) -> tuple[torch.Tensor, dict]:
        cfg = self.cfg
        dev = self.cp.bb.device
        A = torch.tensor([b.advantage for b in batch], device=dev)  # constants: no gradient through the env
        w = torch.tensor([b.weight for b in batch], device=dev)
        # operation factor
        scores = self.cp.bb.score([b.prompt for b in batch], [b.op_cands for b in batch],
                                  prefix_cache=self.cp.policy.cfg.prefix_cache,
                                  vocab_restrict=self.cp.policy.cfg.vocab_restrict)
        op_new = torch.stack([torch.log_softmax(s, 0)[b.op_index] for s, b in zip(scores, batch)])
        op_old = torch.tensor([b.op_logprob_old for b in batch], device=dev)
        # content factor (exact stored ids)
        lp, mask, logd = self.cp.content_log_probs([b.gen_prompt for b in batch], [b.token_ids for b in batch],
                                                   return_logdists=True)
        old = torch.zeros_like(lp)
        for k, b in enumerate(batch):
            old[k, : len(b.token_logprobs_old)] = torch.tensor(b.token_logprobs_old, device=dev)
        maskf = mask.float()

        def surrogate(new, old_, a):
            ratio = torch.exp(new - old_)
            return torch.min(ratio * a, torch.clamp(ratio, 1 - cfg.clip_eps, 1 + cfg.clip_eps) * a), ratio

        s_tok, r_tok = surrogate(lp, old, A[:, None])
        s_tok = s_tok * maskf
        n_tok = maskf.sum(-1).clamp(min=1)
        content_obj = s_tok.sum(-1) if cfg.token_reduction == "sum" else s_tok.sum(-1) / n_tok
        s_op, r_op = surrogate(op_new, op_old, A)
        per_seq = content_obj + s_op
        pg = -(w * per_seq).sum() / w.sum()
        loss = pg
        stats = {"pg_loss": float(pg.detach()), "mean_adv": float(A.mean()),
                 "token_ratio_mean": float((r_tok * maskf).sum() / maskf.sum()),
                 "token_clipfrac": float((((r_tok - 1).abs() > cfg.clip_eps).float() * maskf).sum() / maskf.sum()),
                 "content_tokens": float(maskf.sum()), "seq_logprob_mean": float((lp * maskf).sum(-1).mean().detach())}
        ent = -(logd.exp() * logd).sum(-1)
        stats["token_entropy"] = float((ent * maskf).sum() / maskf.sum())
        if cfg.kl_coef > 0 and self.ref is not None:
            with torch.no_grad():
                _, _, ref_logd = self.ref.content_log_probs([b.gen_prompt for b in batch],
                                                            [b.token_ids for b in batch], return_logdists=True)
            kl = (logd.exp() * (logd - ref_logd)).sum(-1)  # exact per-position KL over the vocabulary
            kl = (kl * maskf).sum(-1).mean()
            loss = loss + cfg.kl_coef * kl
            stats["kl_ref"] = float(kl.detach())
        return loss, stats

    def update(self, episodes: Sequence[Sequence[Transition]], imagined: Sequence[ContentRLStep] = ()) -> dict:
        steps, rejected = build_content_rl_steps(episodes, self.cfg)
        steps = steps + list(imagined)
        if not steps:
            return {"skipped": 1.0, "rejected": rejected}
        acc: dict[str, list[float]] = defaultdict(list)
        self.cp.policy.train()
        for _ in range(self.cfg.epochs):
            self.rng.shuffle(steps)
            for i in range(0, len(steps), self.cfg.minibatch_size):
                mb = steps[i: i + self.cfg.minibatch_size]
                loss, st = self.loss(mb)
                upd = self.trainer.step(loss)
                for k, v in {**st, **upd}.items():
                    acc[k].append(v)
        self.version += 1
        self.cp.checkpoint_id = f"content-rl-v{self.version}"
        out = {k: float(np.nanmean(v)) for k, v in acc.items()}
        out.update(n_steps=len(steps), n_imagined=sum(s.imagined for s in steps),
                   **{f"rejected[{k}]": v for k, v in rejected.items()})
        return out


# --------------------------------------------------------------------------- imagination


class ContentImaginationConfig(BaseModel):
    model_config = ConfigDict(extra="forbid")
    drafts_per_state: int = 4
    states_per_update: int = 8
    max_epistemic: float = 0.15
    weight: float = 0.5


@torch.no_grad()
def imagined_content_steps(cp: ContentGeneratingPolicy, wm: ContentConditionedWorldModel, states: Sequence[Transition],
                           cfg: ContentImaginationConfig, seed: int = 0) -> tuple[list[ContentRLStep], dict]:
    """On-policy drafts (T=1) scored by the world model: imagined advantage = predicted
    P(objective) - group mean. Filtered by ensemble uncertainty. Never stored as real outcomes."""
    from agentrs.actions.schema import Action, try_parse_action
    from agentrs.content.policy import generation_prompt

    gen = torch.Generator().manual_seed(seed)
    out, kept, cut, preds_all = [], 0, 0, []
    for t in states:
        a = try_parse_action(t.action)
        sa = t.semantic_action
        if a is None or sa is None or not t.belief_prompt or not sa.op_candidates:
            continue
        gp = generation_prompt(t.belief_prompt, a.name or "")
        drafts = cp.sample_content([gp] * cfg.drafts_per_state, temperature=1.0, generator=gen)
        acts = [Action.submit(a.name or "", d["content"]).to_str() for d in drafts]
        preds = wm.predict_content(t.goal, t.observation, acts, [])
        ps = np.asarray([p.p_objective for p in preds])
        preds_all += ps.tolist()
        for d, p in zip(drafts, preds):
            if p.epistemic > cfg.max_epistemic:
                cut += 1
                continue
            kept += 1
            out.append(ContentRLStep(prompt=t.belief_prompt, op_cands=sa.op_candidates, op_index=sa.op_index,
                                     op_logprob_old=float(cp.op_log_probs([t.belief_prompt], [[try_parse_action(c) for c in
                                                                                                 t.candidates]])[0][
                                         sa.op_index]) if t.candidates else 0.0,
                                     gen_prompt=gp, token_ids=d["ids"], token_logprobs_old=d["logprobs"],
                                     advantage=float(p.p_objective - ps.mean()), checkpoint=cp.checkpoint_id,
                                     weight=cfg.weight, imagined=True))
    return out, {"imagined_drafts": kept, "imagined_cut_by_uncertainty": cut,
                 "imagined_mean_p_objective": float(np.mean(preds_all)) if preds_all else None}
