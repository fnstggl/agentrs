"""Source adapters: one per authorised information source.

Each adapter declares what it is allowed to do (``SourceDeclaration``) and implements three calls:
``poll(cursor)`` (new raw events since a cursor), ``fetch_state(ref)`` (current public state of an
observed object, for scheduled follow-ups) and ``normalize(raw)`` (raw event → new
``ObservedActorAction`` or a follow-up event for a known object). The network enforces the
declaration; adapters never bypass authentication, quotas or access controls.
"""

from __future__ import annotations

import abc
import json
from pathlib import Path
from typing import Any, Literal

from pydantic import BaseModel, ConfigDict, Field

from agentrs.data.observed_actor_action import ObservedAction, ObservedActorAction

AccessMethod = Literal["self_hosted_feed", "licensed_dataset", "authorized_api", "rss", "webhook", "consented_demos",
                       "agent_traces", "live_web"]
PROHIBITED_DEFAULT = ["private_messages", "credentials", "private_accounts", "sensitive_personal_data",
                      "payment_details"]


class CollectionLimits(BaseModel):
    model_config = ConfigDict(extra="forbid")

    requests_per_minute: float = 60.0
    max_new_actions_per_day: int | None = None
    max_follow_ups_per_action: int = 16


class SourceDeclaration(BaseModel):
    model_config = ConfigDict(extra="forbid")

    source_id: str
    name: str
    access_method: AccessMethod
    operator: str  # who runs the source / grants access
    simulated: bool = False  # all activity generated by simulated actors inside our own environment
    allowed_data_categories: list[str]
    prohibited_categories: list[str] = Field(default_factory=lambda: list(PROHIBITED_DEFAULT))
    training_authorized: bool = False  # explicit permission to use the data for model training
    authorization_ref: str | None = None  # agreement / license id; required for external sources
    collection_limits: CollectionLimits = Field(default_factory=CollectionLimits)
    retention_days: float | None = None
    redistribution_allowed: bool = False
    event_types: list[str] = Field(default_factory=list)
    min_poll_interval_s: float = 10.0
    backfill_allowed: bool = False
    deletion_policy: Literal["retain", "redact", "purge"] = "redact"
    pii_redaction: bool = True
    time_base: str = "real"
    valid_until_wall: float | None = None
    notes: str = ""


class RawEvent(BaseModel):
    provider_event_id: str
    type: str
    at: float | None = None  # environment time, if the provider reports it
    object_ref: str | None = None
    data: dict[str, Any] = Field(default_factory=dict)


class FollowUp(BaseModel):
    """An event about an object we already track (reply, edit, moderation, deletion, ...)."""

    object_ref: str
    type: str
    env_event_time: float | None
    actor_ref: str | None
    by_original_actor: bool | None
    provider_event_id: str
    payload: dict[str, Any] = Field(default_factory=dict)
    categories: list[str] = Field(default_factory=list)


class SourceError(RuntimeError):
    def __init__(self, msg: str, status: int = 0, retry_after: float | None = None):
        super().__init__(msg)
        self.status = status
        self.retry_after = retry_after


class SourceAdapter(abc.ABC):
    declaration: SourceDeclaration

    @abc.abstractmethod
    def now(self) -> float:
        """Current time in the source's time base."""

    @abc.abstractmethod
    def poll(self, cursor: Any) -> tuple[list[RawEvent], Any]: ...

    @abc.abstractmethod
    def fetch_state(self, object_ref: str) -> tuple[dict, str]:
        """(observation payload, completeness). Payload keys: counts, state, continuous, occurred, occurred_at."""

    @abc.abstractmethod
    def normalize(self, raw: RawEvent) -> list[ObservedActorAction | FollowUp]: ...

    def categories_of(self, item: ObservedActorAction | FollowUp) -> list[str]:
        if isinstance(item, FollowUp):
            return item.categories
        return list(item.permission_metadata.get("categories", []))


class JsonlDatasetAdapter(SourceAdapter):
    """A licensed / permissioned dataset of observed actions with outcomes, one JSON object per line:
    ``{"id", "time", "actor_type", "context": {...}, "operation", "content", "follow_ups": [...],
    "states": [{"t", "payload"}]}``. ``time_base`` must be declared (``real`` for historical data)."""

    def __init__(self, declaration: SourceDeclaration, path: str | Path, now_fn=None):
        self.declaration = declaration
        self.rows = [json.loads(line) for line in Path(path).read_text().splitlines() if line.strip()]
        self._by_id = {str(r["id"]): r for r in self.rows}
        self._now_fn = now_fn

    def now(self) -> float:
        if self._now_fn:
            return self._now_fn()
        return max([float(r["time"]) for r in self.rows] + [0.0]) + 1.0

    def poll(self, cursor):
        start = int(cursor or 0)
        batch = self.rows[start:start + 500]
        return [RawEvent(provider_event_id=f"row{start + i}", type="row", at=float(r["time"]), object_ref=str(r["id"]),
                         data=r) for i, r in enumerate(batch)], start + len(batch)

    def fetch_state(self, object_ref: str):
        r = self._by_id.get(object_ref)
        if r is None:
            raise SourceError("unknown object", 404)
        now = self.now()
        st = [s for s in r.get("states", []) if s["t"] <= now]
        if not st:
            return {}, "missing"
        return st[-1]["payload"], "complete"

    def normalize(self, raw: RawEvent):
        r = raw.data
        out: list = [ObservedActorAction(
            source_id=self.declaration.source_id, provider_object_id=str(r["id"]), actor_type=r.get("actor_type", "unknown"),
            action_time=float(r["time"]), action_time_known=True, observation_time=float(r["time"]),
            time_base=self.declaration.time_base, context_before=r.get("context", {}), context_complete=False,
            action=ObservedAction(operation=r["operation"], content=r.get("content")), goal=None, goal_known=False,
            provenance={"dataset": self.declaration.name, "license": self.declaration.authorization_ref},
            permission_metadata={"categories": r.get("categories", ["public_posts"])},
            missing=["goal"], env_id=r.get("env_id", "dataset"), group=r.get("group", "dataset"))]
        for i, f in enumerate(r.get("follow_ups", [])):
            out.append(FollowUp(object_ref=str(r["id"]), type=f["type"], env_event_time=f.get("t"), actor_ref=None,
                                by_original_actor=f.get("by_original_actor"), provider_event_id=f"{r['id']}:{i}",
                                payload=f.get("payload", {}), categories=f.get("categories", ["public_replies"])))
        return out


class UnauthorizedLiveSource(SourceAdapter):
    """Placeholder for external live-web providers (e.g. a Reddit adapter). It refuses to operate
    unless its declaration carries explicit training authorisation and an authorisation reference;
    public visibility alone is not treated as permission to collect or train."""

    def __init__(self, declaration: SourceDeclaration):
        if not (declaration.training_authorized and declaration.authorization_ref):
            raise PermissionError(f"{declaration.source_id}: live-web collection for model training needs an explicit "
                                  "authorisation from the platform (authorization_ref); none was provided")
        self.declaration = declaration

    def now(self):  # pragma: no cover - never constructed without authorisation
        raise NotImplementedError

    def poll(self, cursor):  # pragma: no cover
        raise NotImplementedError("implement against the provider's authorised API")

    def fetch_state(self, object_ref):  # pragma: no cover
        raise NotImplementedError

    def normalize(self, raw):  # pragma: no cover
        raise NotImplementedError
