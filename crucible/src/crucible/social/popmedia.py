"""What population creators make besides text (MASTER_SPEC 4.2): image cards, narrated audio pieces and narrated
slide videos with subtitles, rendered with the lightweight studio tools of workstream D's media layer
(`crucible.semantic.media`: Pillow text rendering, FFmpeg's built-in flite speech synthesiser, FFmpeg video assembly
and mov_text subtitles - every native tool jailed) from the creator's own piece of writing (`population.writing`,
real news text). Nothing is generated by a large model; no artifact carries a quality, relevance or virality figure.

The renderers are pure functions of their inputs (bytes only). Population code calls them through
`social.render.recorded_bytes`, so a world records each artifact once and replay, regeneration and forks never run a
tool again.

* `image_card(title, lead, style)`  - a poster/thumbnail-style card: the title (and the lead sentence) drawn with the
  creator's palette, typeface and size. This is the image genre the shared space's image map is fitted and
  measured on (`semantic.space.fit`: rendered news titles), so the audience reads its topic from the pixels.
* `narration(text, style)`           - speech synthesis of the piece (WAV) with a short melodic jingle; the space
  transcribes it (whisper) and the audience reads its topic from the transcript.
* `slideshow(title, sentences, style, min_s, max_s)` - one slide per sentence (title slide first), narrated, the
  slides timed to the narration, the narration's text as a subtitle track (MP4, mov_text).

Limits (FIDELITY_REGISTER `population-media-creation`): images are text cards, not photographs; voices are flite's
five synthetic voices; videos are slide shows. No real image, audio or video corpus exists on this machine.
"""
from __future__ import annotations

import io
import wave

import numpy as np

VOICES = ("awb", "kal16", "rms", "slt", "kal")
PALETTES = (("#111111", "#ffffff"), ("#ffffff", "#1d3557"), ("#d00000", "#ffe600"), ("#003049", "#eae2b7"),
            ("#ffffff", "#2a9d8f"), ("#222222", "#f4a261"), ("#f1faee", "#e63946"), ("#0b090a", "#bfd200"))
FAMILIES = ("sans", "serif")
SCALES = ("C4 D4 E4 G4 A4 C5", "A3 C4 D4 E4 G4 A4", "D4 E4 F#4 A4 B4 D5", "E4 G4 A4 B4 D5 E5")
SR = 16000
WORDS_PER_S = 2.6           # flite's speaking rate at rate 1.0 (measured by the duration of the rendered WAV)


def style_of(seed: int) -> dict:
    """A creator's visual and audio style (palette, typeface, voice, jingle scale), stable per creator."""
    r = np.random.default_rng(int(seed) & 0x7FFFFFFF)
    return {"palette": int(r.integers(0, len(PALETTES))), "family": FAMILIES[int(r.integers(0, len(FAMILIES)))],
            "bold": bool(r.integers(0, 2)), "size": int(r.integers(30, 48)), "voice": VOICES[int(r.integers(0, 5))],
            "rate": round(float(r.uniform(0.9, 1.15)), 3), "scale": int(r.integers(0, len(SCALES))),
            "bpm": int(r.integers(84, 132))}


def image_card(title: str, lead: str, style: dict, *, width: int = 448) -> bytes:
    from ..semantic import media as MD
    fg, bg = PALETTES[int(style["palette"]) % len(PALETTES)]
    text = title if not lead else f"{title}\n\n{lead}"
    size = int(style["size"]) if not lead else max(20, int(style["size"]) * 2 // 3)
    return MD.render_text_image(text, width=width, height=width, font_size=size, color=fg, background=bg,
                                align="center", family=style.get("family", "sans"), bold=bool(style.get("bold")))


def _wav_seconds(data: bytes) -> float:
    with wave.open(io.BytesIO(data)) as w:
        return w.getnframes() / float(w.getframerate())


def _wav_samples(data: bytes) -> np.ndarray:
    with wave.open(io.BytesIO(data)) as w:
        x = np.frombuffer(w.readframes(w.getnframes()), dtype="<i2").astype(np.float32) / 32768.0
    return x


def _jingle(style: dict, seconds: float = 2.0) -> np.ndarray:
    from ..semantic import media as MD
    notes = SCALES[int(style["scale"]) % len(SCALES)].split()
    r = np.random.default_rng(int(style["scale"]) * 31 + int(style["bpm"]))
    steps = max(2, int(seconds * style["bpm"] / 60.0 * 2))
    seq = [notes[int(r.integers(0, len(notes)))] for _ in range(steps)]
    return MD.synth_melody(seq, bpm=float(style["bpm"]), beats=0.5, sr=SR, amp=0.35)


def narration(text: str, style: dict, *, jingle: bool = True) -> bytes:
    """A narrated audio piece of `text` (16 kHz mono speech after a short jingle), Ogg Opus at 24 kbit/s."""
    from ..semantic import media as MD
    speech = _wav_samples(MD.synth_speech(text, voice=style["voice"], sr=SR, rate=float(style["rate"])))
    parts = [_jingle(style), np.zeros(int(0.3 * SR), np.float32), speech] if jingle else [speech]
    wav = MD.wav_bytes(np.concatenate(parts).astype(np.float32), SR)
    return MD.transcode(wav, "opus", audio_bitrate="24k")


def slideshow(title: str, sentences: list[str], style: dict, *, min_s: float = 0.0, max_s: float = 3600.0,
              size: tuple[int, int] = (640, 360)) -> bytes:
    """A narrated slide video: title slide, then one slide per sentence, each shown while its words are spoken (by
    word count share of the narration), subtitles = the narrated text. Padded to `min_s` by holding the last slide."""
    from ..semantic import media as MD
    fg, bg = PALETTES[int(style["palette"]) % len(PALETTES)]
    texts = [title] + [s for s in sentences if s.strip()]
    speech = MD.synth_speech(" ".join(texts), voice=style["voice"], sr=SR, rate=float(style["rate"]))
    total = _wav_seconds(speech)
    words = np.array([max(1, len(t.split())) for t in texts], np.float64)
    durs = list(np.maximum(1.0, total * words / words.sum()))
    if sum(durs) < min_s:
        durs[-1] += min_s - sum(durs)
    if sum(durs) > max_s:
        raise MD.MediaError(f"narration of {sum(durs):.0f} s exceeds {max_s:.0f} s")
    slides = [MD.render_text_image(t, width=size[0], height=size[1], font_size=int(style["size"]) if i == 0 else
                                   max(18, int(style["size"]) * 2 // 3), color=fg, background=bg, align="center",
                                   family=style.get("family", "sans"), bold=bool(style.get("bold")) and i == 0)
              for i, t in enumerate(texts)]
    from . import render
    video = render.slides_video(slides, [round(d, 3) for d in durs], speech, fps=5)
    cues, t0 = [], 0.0
    for t, d in zip(texts, durs):
        cues.append((t0, t0 + d, t))
        t0 += d
    return MD.add_subtitles(video, cues)
