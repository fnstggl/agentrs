"""Run the Crucible 4.0 acceptance tests A-P and record what they measured.

Each test runs under pytest with CRUCIBLE_RECORD_ACCEPTANCE=1, in its own process, so a crash in one is recorded as
that test's failure. The outcome in each record comes from pytest, not from the test. Output:

    docs/experiments/acceptance/<letter>_<name>.json   claim, measured numbers, caveats, reproduce command, outcome
    docs/experiments/acceptance/summary.json           one row per test
    docs/ACCEPTANCE.md                                 the same as a table

    cd crucible && python examples/run_acceptance.py                 # all of them
    cd crucible && python examples/run_acceptance.py --only A,I,M    # some of them (other rows are kept)

Must run outside any tool sandbox: tests that execute agent code use the Crucible sandbox (root, Landlock, seccomp).
Test N clones the repository's HEAD: commit before running it.
"""
from __future__ import annotations

import argparse
import json
import os
import re
import subprocess
import sys
import time

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "docs", "experiments", "acceptance")
TITLES = {"A": "Real software creation", "B": "Multiple viable strategies", "C": "Unknown mechanism discovery",
          "D": "Structural transfer", "E": "Autonomous competition", "F": "Cooperation",
          "G": "Invention and second-order effects", "H": "Long-term sustainability", "I": "Genuine customer value",
          "J": "Reward-hacking resistance", "K": "Architecture-neutral evaluation", "L": "Parametric learning",
          "M": "Reproducibility", "N": "Clean installation", "O": "Independent generalization", "P": "Security"}


def node_ids() -> dict[str, str]:
    text = open(os.path.join(ROOT, "tests", "test_acceptance.py")).read()
    return {m.group(1): f"tests/test_acceptance.py::test_{m.group(1)}_{m.group(2)}"
            for m in re.finditer(r"^def test_([A-P])_(\w+)\(", text, re.M)}


def run_one(letter: str, node: str, timeout: int) -> dict:
    name = node.split("::test_", 1)[1]
    path = os.path.join(OUT, f"{name}.json")
    if os.path.exists(path):
        os.remove(path)                     # a stale record must never stand in for this run
    env = dict(os.environ, CRUCIBLE_RECORD_ACCEPTANCE="1")
    t0 = time.time()
    try:
        p = subprocess.run([sys.executable, "-m", "pytest", "-q", "-p", "no:cacheprovider", "--tb=short", node], cwd=ROOT,
                           env=env, capture_output=True, text=True, timeout=timeout)
        tail, code = p.stdout.strip().splitlines()[-1] if p.stdout.strip() else "", p.returncode
    except subprocess.TimeoutExpired:
        tail, code = f"timed out after {timeout}s", -1
    row = {"test": letter, "title": TITLES[letter], "node": node, "pytest_exit": code, "pytest_summary": tail,
           "wall_s": round(time.time() - t0, 1), "record": os.path.relpath(path, ROOT)}
    if code == 0 and "skipped" in tail:
        row["result"] = "SKIPPED"
    elif code == 0:
        row["result"] = "PASSED"
    else:
        row["result"] = "FAILED"
    if os.path.exists(path):
        with open(path) as fh:
            rec = json.load(fh)
        row["claim"], row["caveats"] = rec.get("claim", ""), rec.get("caveats", [])
    else:
        row["record"] = None
    return row


def write_markdown(rows: dict[str, dict]) -> None:
    lines = ["# Crucible 4.0 acceptance tests", "",
             "Generated by `examples/run_acceptance.py`. The result column is what pytest reported for that test. "
             "Measured numbers are in the linked JSON record; caveats are part of the result.", "",
             "| test | title | result | time | record | main caveat |", "|---|---|---|---|---|---|"]
    for k in sorted(rows):
        r = rows[k]
        cav = (r.get("caveats") or [""])[0].replace("|", "\\|")
        rec = f"[json](experiments/acceptance/{os.path.basename(r['record'])})" if r.get("record") else "none"
        lines.append(f"| {k} | {r['title']} | **{r['result']}** | {r['wall_s']:.0f} s | {rec} | {cav} |")
    lines += ["", "Reproduce one test: `cd crucible && python -m pytest -q 'tests/test_acceptance.py::test_A_real_software_creation'`",
              "(tests that run agent code need root, Landlock and seccomp).", ""]
    with open(os.path.join(ROOT, "docs", "ACCEPTANCE.md"), "w") as fh:
        fh.write("\n".join(lines))


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--only", default="")
    ap.add_argument("--timeout", type=int, default=3000)
    a = ap.parse_args()
    os.makedirs(OUT, exist_ok=True)
    nodes = node_ids()
    want = [x.strip() for x in a.only.split(",") if x.strip()] or sorted(nodes)
    missing = [x for x in want if x not in nodes]
    if missing:
        raise SystemExit(f"no such test: {missing}")
    path = os.path.join(OUT, "summary.json")
    rows = json.load(open(path))["tests"] if os.path.exists(path) else {}
    for k in want:
        rows[k] = run_one(k, nodes[k], a.timeout)
        print(f"{k} {rows[k]['title']:40s} {rows[k]['result']:8s} {rows[k]['wall_s']:7.0f}s  {rows[k]['pytest_summary']}",
              flush=True)
        commit = subprocess.run(["git", "rev-parse", "HEAD"], cwd=ROOT, capture_output=True, text=True).stdout.strip()
        dirty = bool(subprocess.run(["git", "status", "--porcelain", "--", "src", "tests"], cwd=ROOT, capture_output=True,
                                    text=True).stdout.strip())
        with open(path, "w") as fh:
            json.dump({"commit": commit, "tree_had_uncommitted_changes": dirty,
                       "recorded_at": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()), "tests": rows}, fh, indent=1)
        write_markdown(rows)
    n = {r: sum(1 for x in rows.values() if x["result"] == r) for r in ("PASSED", "FAILED", "SKIPPED")}
    print(n)


if __name__ == "__main__":
    main()
